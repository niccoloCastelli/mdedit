#!/usr/bin/env python3
"""Copy the Lucide icons mdedit uses out of an unpacked Lucide release.

Usage: python3 -I assets/icons/update.py <unzipped lucide-icons-X.Y.Z dir>

The release zip comes from https://github.com/lucide-icons/lucide/releases
(`lucide-icons-<version>.zip`). Names in ICONS may be canonical names or
Lucide aliases; files are written under their canonical name, with the
stroke width set to 1.5 (DESIGN_SYSTEM 5). The script also regenerates
crates/mdedit-theme/src/icon_list.rs, so adding an icon is: add its name
here, rerun, commit.
"""

import json
import pathlib
import sys

# Icons the UI uses (DESIGN_SYSTEM 5-8). Keep sorted by area.
ICONS = [
    # Formatting (toolbar, slash menu, Format menu)
    "bold", "italic", "strikethrough", "code", "square-code", "link",
    "heading", "heading-1", "heading-2", "heading-3", "heading-4",
    "heading-5", "heading-6", "list", "list-ordered", "list-todo", "quote",
    "table", "image", "minus", "type",
    # Files and sidebar
    "file", "file-text", "file-plus", "file-down", "folder", "folder-open",
    "folder-plus", "list-tree", "search", "replace", "save", "download",
    "upload", "trash-2", "external-link", "copy",
    # Git and sync
    "git-branch", "git-commit-horizontal", "git-merge", "history", "tag",
    "cloud", "cloud-off", "refresh-cw",
    # Comments
    "message-square", "message-square-plus", "message-square-text",
    # Modes and layout
    "eye", "pencil", "columns-2", "panel-left", "panel-right", "maximize-2",
    "minimize-2", "book-open",
    # Generic UI
    "settings", "x", "plus", "check", "chevron-down", "chevron-right",
    "chevron-left", "chevron-up", "menu", "ellipsis", "more-vertical",
    "undo-2", "redo-2", "sun", "moon", "monitor", "circle-alert",
    "triangle-alert", "info", "circle-check", "lock",
]

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "icons" / "lucide"
LIST_RS = ROOT / "crates" / "mdedit-theme" / "src" / "icon_list.rs"


def main() -> None:
    src = pathlib.Path(sys.argv[1]) / "icons"
    aliases = {}
    for meta in src.glob("*.json"):
        for alias in json.loads(meta.read_text()).get("aliases", []):
            name = alias["name"] if isinstance(alias, dict) else alias
            aliases[name] = meta.stem

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.svg"):
        old.unlink()

    entries = {}  # requested name -> canonical file stem
    for name in ICONS:
        canonical = name if (src / f"{name}.svg").exists() else aliases.get(name)
        if canonical is None:
            sys.exit(f"unknown Lucide icon: {name}")
        svg = (src / f"{canonical}.svg").read_text()
        svg = svg.replace('stroke-width="2"', 'stroke-width="1.5"')
        (OUT / f"{canonical}.svg").write_text(svg)
        entries[canonical] = canonical
        entries[name] = canonical

    lines = [
        "// Generated by assets/icons/update.py. Do not edit.",
        "",
        "/// (name, SVG bytes), sorted by name. Aliases point at the same file.",
        "pub(crate) const ICONS: &[(&str, &[u8])] = &[",
    ]
    for name in sorted(entries):
        path = f"../../../assets/icons/lucide/{entries[name]}.svg"
        lines.append(f'    ("{name}", include_bytes!("{path}")),')
    lines.append("];")
    LIST_RS.write_text("\n".join(lines) + "\n")
    print(f"{len(set(entries.values()))} icons, {len(entries)} names")


if __name__ == "__main__":
    main()
